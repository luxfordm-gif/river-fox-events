/**
 * Old Lollipop Balloons URLs → River Fox Events pages.
 *
 * This is the ONE place to edit old-domain redirects. `scripts/postbuild.mjs`
 * turns the lists below into Netlify rules and writes them at the top of
 * dist/_redirects (above whatever is in public/_redirects).
 *
 * How the generated rules behave:
 *
 *   - On the old domain (lollipopballoonssurrey.co.uk, with and without www,
 *     http and https) every rule is a FORCED 301 (`301!`). Forced means it
 *     always wins, even where the new site has a real page at the same path
 *     (e.g. /contact/), so the old domain never serves a copy of the site.
 *     Anything not listed lands on the new home page.
 *
 *   - On the new domain the same old paths also redirect (not forced, so a
 *     real page always wins). Until Nov 2026 the old domain forwarded paths
 *     1:1, so some links now point at e.g.
 *     riverfoxevents.co.uk/location/balloon-arches-near-guildford - this
 *     catches those too.
 *
 * Location pages: Netlify placeholders must fill a whole path segment, so a
 * rule like `/location/balloon-arches-near-:town` does NOT work. Instead we
 * write one rule per town, built from every `/party-styling-<town>` route in
 * src/seo/routes.ts. New location pages get their old-URL redirects
 * automatically. Old towns with no page of their own go to the nearest page
 * via TOWN_FALLBACKS.
 */

export const OLD_HOSTS = [
  "lollipopballoonssurrey.co.uk",
  "www.lollipopballoonssurrey.co.uk",
];

export const NEW_ORIGIN = "https://riverfoxevents.co.uk";

/** Old path → new path. Order doesn't matter; every path is exact. */
export const PAGE_REDIRECTS = [
  // Service pages
  ["/services/balloons", "/balloon-installations/"],
  ["/services/luxury-kids-parties", "/childrens-parties/"],
  ["/services/events", "/milestone-celebrations/"],
  ["/services/corporate", "/corporate-brand-styling/"],

  // Core pages
  ["/about", "/#about"],
  ["/contact", "/contact/"],

  // Older Wix URLs not in the final sitemap (belt-and-braces for stray backlinks)
  ["/contact-us", "/contact/"],
  ["/blog", "/journal/"],
  ["/post/*", "/journal/childrens-party-themes-2026/"],
  ["/services", "/childrens-parties/"],
  ["/services-1", "/childrens-parties/"],
  ["/installations", "/childrens-parties/"],
  ["/portfolio", "/"],
  ["/portfolio-collections/*", "/"],
  ["/blank-1", "/"],
  ["/blank-2", "/"],
  ["/blank-3", "/"],
];

/** Old location URL prefixes. The town slug follows the prefix. */
export const LOCATION_PREFIXES = [
  "/location/balloon-arches-near-",
  "/location/luxury-children-party-styling-",
];

/** Old towns with no River Fox page of their own → nearest location page slug. */
export const TOWN_FALLBACKS = {
  redhill: "reigate",
  elmbridge: "weybridge",
  felbridge: "east-grinstead",
  kingswood: "epsom",
};

/**
 * Paths that would loop if redirected on the new domain (they ARE the new
 * page, because Netlify ignores trailing slashes when matching). Only
 * redirected on the old domain.
 */
const OLD_DOMAIN_ONLY = new Set(["/contact"]);

const pad = (s, n) => (s.length >= n ? s + " " : s + " ".repeat(n - s.length));

/** Every [oldPath, newPath] pair, location pages included. */
export function legacyPairs(ROUTES) {
  const towns = ROUTES.map((r) => r.path.match(/^\/party-styling-([a-z0-9-]+)\/?$/))
    .filter(Boolean)
    .map((m) => m[1]);
  if (towns.length === 0) throw new Error("legacy-redirects: no /party-styling-* routes found");

  for (const [oldTown, target] of Object.entries(TOWN_FALLBACKS)) {
    if (towns.includes(oldTown)) {
      throw new Error(`legacy-redirects: ${oldTown} now has its own page - remove it from TOWN_FALLBACKS`);
    }
    if (!towns.includes(target)) {
      throw new Error(`legacy-redirects: fallback for ${oldTown} points at missing page /party-styling-${target}/`);
    }
  }

  const townMap = [
    ...towns.map((t) => [t, t]),
    ...Object.entries(TOWN_FALLBACKS),
  ];

  const locationPairs = LOCATION_PREFIXES.flatMap((prefix) =>
    townMap.map(([oldTown, newTown]) => [prefix + oldTown, `/party-styling-${newTown}/`]),
  );

  return [...PAGE_REDIRECTS, ...locationPairs, ["/location/*", "/"]];
}

/** The text block that goes at the top of dist/_redirects. */
export function buildLegacyRedirects(ROUTES) {
  const pairs = legacyPairs(ROUTES);
  const lines = [
    "# ── GENERATED by scripts/postbuild.mjs from scripts/legacy-redirects.mjs ──",
    "# Edit scripts/legacy-redirects.mjs, not this block.",
    "",
  ];

  for (const host of OLD_HOSTS) {
    for (const scheme of ["https", "http"]) {
      const origin = `${scheme}://${host}`;
      lines.push(`# Old domain: ${origin}`);
      for (const [from, to] of pairs) {
        lines.push(`${pad(origin + from, 100)}${NEW_ORIGIN}${to}  301!`);
      }
      // Anything else on the old domain → new home page.
      lines.push(`${pad(origin + "/*", 100)}${NEW_ORIGIN}/  301!`);
      lines.push("");
    }
  }

  lines.push("# New domain: old paths that were forwarded here 1:1 before Nov 2026");
  for (const [from, to] of pairs) {
    if (OLD_DOMAIN_ONLY.has(from)) continue;
    lines.push(`${pad(from, 60)}${to}  301`);
  }
  lines.push("", "# ── END GENERATED ──", "");
  return lines.join("\n");
}
